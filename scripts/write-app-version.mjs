/**
 * Writes src/environments/app-version.ts for local and CI builds.
 *
 * Precedence:
 * 1. APP_VERSION env (e.g. GitHub tag ref_name "v1.2.3")
 * 2. "v" + package.json version
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkgPath = path.join(root, 'package.json');
const outPath = path.join(root, 'src/environments/app-version.ts');

const pkg = JSON.parse(await fs.readFile(pkgPath, 'utf8'));
const fromEnv = (process.env.APP_VERSION || '').trim();
const version = fromEnv || `v${pkg.version}`;

const contents = `/* Generated by scripts/write-app-version.mjs — do not edit by hand. */
export const APP_VERSION = ${JSON.stringify(version)} as const;
`;

await fs.mkdir(path.dirname(outPath), { recursive: true });
await fs.writeFile(outPath, contents, 'utf8');
process.stdout.write(`APP_VERSION=${version}\n`);
